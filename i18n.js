class I18nManager {
  constructor() {
    this.lang = this.getStoredLanguage();
    this.listeners = new Set();
  }

  getStoredLanguage() {
    try {
      return localStorage.getItem(STORAGE_KEY) || 'pt';
    } catch {
      return 'pt';
    }
  }

  getLanguage() {
    return this.lang;
  }

  setLanguage(lang) {
    if (lang !== 'pt' && lang !== 'en') lang = 'pt';
    this.lang = lang;
    try {
      localStorage.setItem(STORAGE_KEY, lang);
      document.documentElement.lang = lang === 'pt' ? 'pt-MZ' : 'en';
    } catch (e) {
      console.warn('Could not save language preference:', e);
    }
    this.notify();
  }

  toggleLanguage() {
    const next = this.lang === 'pt' ? 'en' : 'pt';
    this.setLanguage(next);
    return next;
  }

  /**
   * Main translation function
   * @param {string} key
   * @param {Record<string, any>} [params]
   * @returns {string}
   */
  t(key, params = {}) {
    const currentDict = translations[this.lang] || translations.pt;
    let text = currentDict[key] || translations.pt[key] || key;

    if (params && typeof params === 'object') {
      Object.entries(params).forEach(([pKey, pVal]) => {
        text = text.replace(new RegExp(`{${pKey}}`, 'g'), String(pVal));
      });
    }
    return text;
  }

  onChange(callback) {
    this.listeners.add(callback);
    return () => this.listeners.delete(callback);
  }

  notify() {
    this.listeners.forEach(cb => {
      try { cb(this.lang); } catch (e) { console.error('i18n listener error:', e); }
    });
  }
}

export const i18n = new I18nManager();
export const t = (key, params) => i18n.t(key, params);
